/**
 * Standalone HTML viewer export.
 *
 * The drawing is already rasterized to a self-contained SVG by
 * `io/exportImage.ts` (colors and fonts inlined, editor-only layers
 * stripped). This wraps that SVG in a minimal document with no external
 * stylesheets, scripts or fonts, so the resulting `.html` file opens
 * anywhere — emailed, committed to a repository, dropped on a static host,
 * or viewed offline — without needing EnlaceCraft itself.
 */

function escapeHtml(value: string): string {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

function escapeCssColor(value: string): string {
  // The caller controls this today (it comes from the export picker), but
  // keeping it to a conservative CSS-color grammar avoids a stray `;` or
  // `}` turning a future caller-supplied value into extra rules.
  return /^#[0-9a-f]{3,8}$/i.test(value) ? value : "#ffffff";
}

export interface HtmlViewerOptions {
  /** Document title and the browser-tab label. */
  title: string;
  /** Page background. Kept in sync with the white/theme background the SVG
   * itself was exported with, so no theme's ink can land on a contrasting
   * page. */
  background?: string;
  /** Document language, for correct hyphenation and screen readers. */
  lang?: string;
}

/**
 * `svgMarkup` is the serialized SVG root. It is inserted verbatim because it
 * is generated by our own exporter from the live canvas; the untrusted parts
 * (title/lang/background) are escaped or validated here.
 */
export function buildHtmlViewer(svgMarkup: string, options: HtmlViewerOptions): string {
  const title = escapeHtml(options.title.trim() || "EnlaceCraft");
  const background = escapeCssColor(options.background ?? "#ffffff");
  const lang = escapeHtml(options.lang ?? "en");

  return `<!doctype html>
<html lang="${lang}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="generator" content="EnlaceCraft">
<title>${title}</title>
<style>
  :root { color-scheme: light; }
  html, body { height: 100%; }
  body {
    margin: 0;
    background: ${background};
    font-family: system-ui, -apple-system, "Segoe UI", sans-serif;
    display: flex;
    align-items: center;
    justify-content: center;
    overflow: auto;
    padding: 24px;
    box-sizing: border-box;
  }
  .viewer {
    max-width: 100%;
    max-height: 100%;
    display: flex;
    align-items: center;
    justify-content: center;
  }
  .viewer > svg {
    display: block;
    max-width: 100%;
    max-height: calc(100vh - 48px);
    width: auto;
    height: auto;
  }
  @media print {
    body { padding: 0; background: #ffffff; }
    .viewer > svg { max-height: none; }
  }
</style>
</head>
<body>
<main class="viewer" role="img" aria-label="${title}">
${svgMarkup}
</main>
</body>
</html>
`;
}
